        public static Texture2D Get(string portrait)
        {
            if (portrait == "cultist") portrait = "mage";
            if (portrait == "warden") portrait = "knight";
            if (string.IsNullOrEmpty(portrait) || !shapes.ContainsKey(portrait)) portrait = "bandit";
            if (cache.TryGetValue(portrait, out var found)) return found;
            var lines = shapes[portrait].Trim('\n','\r').Split('\n');
            int width = 32, height = 32; var pixels = new Color32[width*height];
            int top = (height-lines.Length)/2;
            for (int y=0;y<lines.Length;y++)
            {
                var line=lines[y].TrimEnd('\r'); int left=(width-line.Length)/2;
                for(int x=0;x<line.Length;x++) if(colors.TryGetValue(line[x],out var color)) pixels[(height-1-top-y)*width+left+x]=color;
            }
            var texture = new Texture2D(width,height,TextureFormat.RGBA32,false) { name="Arvito "+portrait,filterMode=FilterMode.Point,wrapMode=TextureWrapMode.Clamp };
            texture.SetPixels32(pixels); texture.Apply(false,true); cache[portrait]=texture; return texture;
        }
